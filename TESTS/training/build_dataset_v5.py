import collections
import hashlib
import json
import os
import sys

_ROOT = r"C:\PRIMORA PROJECT"
sys.path.insert(0, _ROOT)
sys.path.insert(0, os.path.join(_ROOT, "TRAINING"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import audit_v2 as A2  # noqa: E402
import build_dataset_v4 as BD4  # noqa: E402
from generate_v2 import SCHEMA_VERSION, build_system_context  # noqa: E402

GENERATOR_VERSION = "aurora-brain-v0.5-merge-1"
V4_GENERATOR_VERSION = BD4.GENERATOR_VERSION          # aurora-brain-v0.4-build-1
V2_GENERATOR_VERSION = "aurora-brain-v0.1-seedgen-1"

_HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUTDIR = os.path.join(_HERE, "data", "v5")
V4_DIR = os.path.join(_HERE, "data", "v4")
V2_DIR = os.path.join(_HERE, "data", "v2")

SPLIT_ORDER = BD4.SPLIT_ORDER
TARGET_REPEAT_LIMIT = BD4.TARGET_REPEAT_LIMIT         # 2, unchanged
MERGED_PROVENANCE = "v2"
V4_PROVENANCE = "seed_bank_v4"

# v4 contributes 1,080/180/180; the 217 merged records all land in train.
EXPECTED_RECORDS = {"train": 1297, "validation": 180, "holdout": 180}
EXPECTED_RETAINED = 217

# The two metadata fields that Option 1 is allowed to change. Every other
# field of a copied v4 eval record must hash-identically to its source.
SYSTEM_FIELDS = ("system_ref", "system_fingerprint")


# --------------------------------------------------------------------------
# IO and hashing
# --------------------------------------------------------------------------


def load_jsonl(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def load_source(split: str, data_dir: str) -> list[dict]:
    return load_jsonl(os.path.join(data_dir, f"{split}.jsonl"))


def target_of(row: dict) -> str:
    """The one assistant turn this record supervises (gate semantics)."""
    assistants = [m for m in row["messages"] if m["role"] == "assistant"]
    return assistants[row["train_on"][-1]]["content"]


def last_ask(row: dict) -> str:
    return [m for m in row["messages"] if m["role"] == "user"][-1]["content"]


def content_digest(row: dict) -> str:
    """Stable digest of a record with the system metadata excluded.

    Option 1 is permitted to refresh ``system_ref``/``system_fingerprint`` and
    nothing else, so eval identity is asserted on the content that actually
    matters: id, messages, supervision, seed and membership.
    """
    body = {k: v for k, v in row.items() if k not in SYSTEM_FIELDS}
    payload = json.dumps(body, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def split_digest(rows: list[dict]) -> str:
    """One digest for a whole split: per-record digests, id-sorted, chained."""
    chained = hashlib.sha256()
    for row in sorted(rows, key=lambda r: r["id"]):
        chained.update(content_digest(row).encode("ascii"))
    return chained.hexdigest()


# --------------------------------------------------------------------------
# The audited deterministic selection
# --------------------------------------------------------------------------


def select_v2_records(src: list[dict]) -> list[dict]:
    """The 217-record subset, chosen by the rule the Phase C audit approved.

    Group the ``expect_block`` training records by exact final target. A
    group of one or two is kept whole. A larger group keeps two: the lowest-id
    record of two distinct seeds when the target spans several (so no seed's
    coverage is silently dropped while another is over-represented), else the
    two lowest ids. Nothing is rewritten; the result is sorted by id so the
    selection is stable regardless of input order.
    """
    by_target: dict[str, list[dict]] = collections.defaultdict(list)
    for row in src:
        by_target[target_of(row)].append(row)

    keep: list[dict] = []
    for _text, group in by_target.items():
        group = sorted(group, key=lambda r: r["id"])
        if len(group) <= TARGET_REPEAT_LIMIT:
            keep.extend(group)
            continue
        seeds = sorted({r["seed_id"] for r in group})
        pick: list[dict] = []
        if len(seeds) > 1:
            for sid in seeds:
                candidates = [r for r in group if r["seed_id"] == sid]
                if candidates:
                    pick.append(candidates[0])
                if len(pick) == TARGET_REPEAT_LIMIT:
                    break
        if len(pick) < TARGET_REPEAT_LIMIT:
            pick = group[:TARGET_REPEAT_LIMIT]
        keep.extend(pick)
    return sorted(keep, key=lambda r: r["id"])


# --------------------------------------------------------------------------
# Restamping
# --------------------------------------------------------------------------


def restamp(row: dict, system_ref: str, fingerprint: str,
            provenance: str | None = None) -> dict:
    """Copy a record, refresh only the system metadata (and provenance).

    Every other field - id, messages, train_on, seed_id, split, category,
    note, variant, seed_priority, expect_block, expect_action,
    schema_version, generator_version - is carried over untouched.
    """
    out = dict(row)
    out["system_ref"] = system_ref
    out["system_fingerprint"] = fingerprint
    if provenance is not None:
        out["seed_provenance"] = provenance
    return out


# --------------------------------------------------------------------------
# Build
# --------------------------------------------------------------------------


def build() -> tuple[dict[str, list[dict]], list[str], dict]:
    """Assemble the merge in memory. Nothing touches disk; ``write`` does."""
    problems: list[str] = []

    v4 = {side: load_source(side, V4_DIR) for side in SPLIT_ORDER}
    v2_train = load_source("train", V2_DIR)
    if not all(v4[side] for side in SPLIT_ORDER) or not v2_train:
        return {}, ["a source split is missing under data/v4 or data/v2"], {}

    # The audited selection, from v2's expect_block training records only.
    src = [r for r in v2_train if r.get("expect_block") is True]
    retained = select_v2_records(src)
    if len(retained) != EXPECTED_RETAINED:
        problems.append(
            f"selection returned {len(retained)} records, audit approved "
            f"{EXPECTED_RETAINED}")

    # Live system context. This is the ref every v5 record must carry so
    # load_split/resolve_system_context succeed at training time.
    system_key, composed, capabilities = build_system_context()
    fingerprint = hashlib.sha256(composed.encode("utf-8")).hexdigest()

    records: dict[str, list[dict]] = {
        "train": [restamp(r, system_key, fingerprint) for r in v4["train"]]
        + [restamp(r, system_key, fingerprint, MERGED_PROVENANCE)
           for r in retained],
        "validation": [restamp(r, system_key, fingerprint)
                       for r in v4["validation"]],
        "holdout": [restamp(r, system_key, fingerprint)
                    for r in v4["holdout"]],
    }

    problems += gate_counts(records)
    problems += gate_selection(retained)
    problems += gate_repetition(records)
    problems += gate_eval_identity(records, v4)
    problems += gate_seed_namespaces(records)
    problems += gate_provenance(records)

    info = {
        "system_ref": system_key,
        "system_fingerprint": fingerprint,
        "capabilities": capabilities,
        "record_counts": {side: len(records[side]) for side in SPLIT_ORDER},
        "retained_ids": [r["id"] for r in retained],
        "retained_seeds": sorted({r["seed_id"] for r in retained}),
        "retained_actions": dict(collections.Counter(
            r.get("expect_action") for r in retained)),
        "retained_block_targets": sorted({
            target_of(r) for r in retained if "<prime_request>" in target_of(r)}),
        "source_v4_counts": {side: len(v4[side]) for side in SPLIT_ORDER},
        "source_v2_train": len(v2_train),
        "source_v2_expect_block": len(src),
        "eval_content_digests": {
            side: split_digest(records[side]) for side in ("validation", "holdout")},
        "v4_eval_content_digests": {
            side: split_digest(v4[side]) for side in ("validation", "holdout")},
    }
    return records, problems, info


# --------------------------------------------------------------------------
# Gates
# --------------------------------------------------------------------------


def gate_counts(records: dict[str, list[dict]]) -> list[str]:
    problems: list[str] = []
    for side, want in EXPECTED_RECORDS.items():
        got = len(records.get(side, []))
        if got != want:
            problems.append(f"{side} holds {got} records, expected {want}")
    total = sum(len(records.get(s, [])) for s in SPLIT_ORDER)
    if total != sum(EXPECTED_RECORDS.values()):
        problems.append(f"total {total} records, expected "
                        f"{sum(EXPECTED_RECORDS.values())}")
    return problems


def gate_selection(retained: list[dict]) -> list[str]:
    """The approved 217 must be reproduced exactly, at most twice per target."""
    problems: list[str] = []
    counts = collections.Counter(target_of(r) for r in retained)
    over = {t: n for t, n in counts.items() if n > TARGET_REPEAT_LIMIT}
    for text, times in sorted(over.items(), key=lambda kv: (-kv[1], kv[0])):
        problems.append(
            f"retained subset repeats a target {times} times (limit "
            f"{TARGET_REPEAT_LIMIT}): {text[:60]!r}")
    if len(retained) != len({r["id"] for r in retained}):
        problems.append("retained subset contains duplicate record ids")
    return problems


def gate_repetition(records: dict[str, list[dict]]) -> list[str]:
    """No exact final target supervised more than twice across all splits."""
    counts: collections.Counter = collections.Counter(
        target_of(row) for side in SPLIT_ORDER
        for row in records.get(side, []))
    problems: list[str] = []
    for text, times in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        if times > TARGET_REPEAT_LIMIT:
            problems.append(
                f"target repeated {times} times (limit "
                f"{TARGET_REPEAT_LIMIT}): {text[:60]!r}")
    return problems


def gate_eval_identity(records: dict[str, list[dict]],
                       v4: dict[str, list[dict]]) -> list[str]:
    """v5's eval splits must match v4's content and membership exactly.

    The only permitted divergence is the two system metadata fields refreshed
    by Option 1, so identity is asserted on content digests that exclude them
    and on the id set.
    """
    problems: list[str] = []
    for side in ("validation", "holdout"):
        v5_rows = records.get(side, [])
        v4_rows = v4.get(side, [])
        if sorted(r["id"] for r in v5_rows) != sorted(r["id"] for r in v4_rows):
            problems.append(f"{side}: membership (record ids) drifted from v4")
        if split_digest(v5_rows) != split_digest(v4_rows):
            problems.append(
                f"{side}: content digest differs from v4 (beyond the system "
                f"metadata fields)")
    return problems


def gate_seed_namespaces(records: dict[str, list[dict]]) -> list[str]:
    """v4 and v2 seed id namespaces are disjoint; no seed may straddle splits."""
    problems: list[str] = []
    seed_side: dict[str, set[str]] = collections.defaultdict(set)
    for side in SPLIT_ORDER:
        for row in records.get(side, []):
            seed_side[row.get("seed_id")].add(side)
    for sid, sides in sorted(seed_side.items()):
        if len(sides) > 1:
            problems.append(
                f"{sid}: whole-seed atomicity broken: {sorted(sides)}")
    return problems


def gate_provenance(records: dict[str, list[dict]]) -> list[str]:
    """v4 records keep seed_bank_v4; the 217 merged records are stamped v2."""
    problems: list[str] = []
    for side in SPLIT_ORDER:
        for row in records.get(side, []):
            gen = row.get("generator_version")
            prov = row.get("seed_provenance")
            if gen == V4_GENERATOR_VERSION and prov != V4_PROVENANCE:
                problems.append(
                    f"{row.get('id')}: v4 record has provenance {prov!r}")
            elif gen == V2_GENERATOR_VERSION and prov != MERGED_PROVENANCE:
                problems.append(
                    f"{row.get('id')}: merged record has provenance {prov!r}")
            elif gen not in (V4_GENERATOR_VERSION, V2_GENERATOR_VERSION):
                problems.append(
                    f"{row.get('id')}: unexpected generator_version {gen!r}")
    return problems


# --------------------------------------------------------------------------
# Write
# --------------------------------------------------------------------------


def write(records: dict[str, list[dict]], info: dict,
          outdir: str = DEFAULT_OUTDIR) -> dict[str, int]:
    os.makedirs(outdir, exist_ok=True)
    written: dict[str, int] = {}
    for side in SPLIT_ORDER:
        path = os.path.join(outdir, f"{side}.jsonl")
        with open(path, "w", encoding="utf-8") as handle:
            for row in records[side]:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        written[side] = len(records[side])

    with open(os.path.join(outdir, "HOLDOUT_PROTECTED.json"), "w",
              encoding="utf-8") as handle:
        json.dump({
            "split": "holdout",
            "count": written["holdout"],
            "status": "protected - evaluation only",
            "rule": ("Not used during generation, tuning or wording decisions. "
                     "Read only when the holdout is actually being scored."),
            "generator_version": GENERATOR_VERSION,
            "schema_version": SCHEMA_VERSION,
            "system_ref": info["system_ref"],
            "note": ("Holdout content is byte-identical to v4's holdout apart "
                     "from the refreshed system metadata fields."),
        }, handle, indent=2)

    with open(os.path.join(outdir, "build_manifest.json"), "w",
              encoding="utf-8") as handle:
        json.dump({
            "generator_version": GENERATOR_VERSION,
            "schema_version": SCHEMA_VERSION,
            "system_ref": info["system_ref"],
            "system_fingerprint": info["system_fingerprint"],
            "capabilities": info["capabilities"],
            "record_counts": written,
            "sources": {
                "v4": {"dir": "data/v4", "generator_version": V4_GENERATOR_VERSION,
                       "counts": info["source_v4_counts"],
                       "provenance": V4_PROVENANCE,
                       "system_ref_refreshed": True},
                "v2": {"dir": "data/v2", "generator_version": V2_GENERATOR_VERSION,
                       "train_records": info["source_v2_train"],
                       "expect_block_records": info["source_v2_expect_block"],
                       "retained": len(info["retained_ids"]),
                       "provenance": MERGED_PROVENANCE,
                       "system_ref_refreshed": True},
            },
            "retention": {
                "rule": ("at most TARGET_REPEAT_LIMIT=2 records per exact "
                         "final target; prefer distinct seeds, else lowest ids"),
                "retained": len(info["retained_ids"]),
                "retained_ids": info["retained_ids"],
                "retained_seeds": info["retained_seeds"],
                "retained_actions": info["retained_actions"],
                "retained_block_targets": info["retained_block_targets"],
            },
            "eval_identity": {
                "note": ("validation/holdout content digests exclude only "
                         "system_ref/system_fingerprint; they must equal v4's"),
                "v5": info["eval_content_digests"],
                "v4": info["v4_eval_content_digests"],
            },
            "target_repeat_limit": TARGET_REPEAT_LIMIT,
        }, handle, indent=2)
    return written


def main() -> int:
    outdir = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUTDIR
    records, problems, info = build()
    if problems:
        print(f"REFUSING TO WRITE: {len(problems)} problem(s)")
        for problem in problems[:40]:
            print(f"  FAIL {problem}")
        return 1
    written = write(records, info, outdir)
    print("=" * 72)
    print("AURORA BRAIN v0.5 - MERGED DATASET BUILD")
    print("=" * 72)
    for side in SPLIT_ORDER:
        print(f"  {side:<11}: {written[side]:>5} records")
    print(f"  merged     : {len(info['retained_ids'])} v2 expect_block records "
          f"({len(info['retained_seeds'])} seeds)")
    print(f"  system_ref : {info['system_ref']}")
    print(f"  output     : {outdir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
