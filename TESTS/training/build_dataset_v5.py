"""Build the Aurora Brain v0.5 merged dataset.

v0.5 is a MERGE, not a fresh generation. It takes the already-built v0.4
corpus (1,440 records, authored against ``seed_bank_v4``) and appends the
audited, deterministic subset of v0.2's ``expect_block`` training records so
the trainer finally sees request-block supervision. Everything else is
preserved.

What it does:

*   sources      - v4 train/validation/holdout are read verbatim from
                   ``data/v4``; v2 train is read verbatim from ``data/v2``.
                   Neither source directory is ever written to;
*   selection    - of v2's 499 ``expect_block`` training records exactly 217
                   are kept under the audited deterministic rule: one exact
                   final target is supervised at most ``TARGET_REPEAT_LIMIT``
                   times, preferring records from distinct seeds when a target
                   spans several, else the lowest record ids. The rule is
                   pure and order-independent (the result is sorted by id), so
                   re-running it always yields the same 217;
*   restamping   - Phase A2 expanded ``DEFAULT_SYSTEM_INSTRUCTION``, which is
                   a component of the dataset-level system context, so the
                   live runtime now composes ``aurora.system.v1@d7717dbb...``
                   while every v2/v4 record on disk still carries the stale
                   ``...@bafa84d4...``. ``load_split`` resolves a record's
                   ``system_ref`` against the live instruction and raises when
                   they disagree, so a stale ref is fatal for training. Every
                   v5 record is therefore restamped with the live ref and its
                   matching fingerprint. This touches only the two system
                   metadata fields; ids, messages, ``train_on``, ``seed_id``
                   and split membership are copied unchanged;
*   provenance   - the 217 merged records are stamped ``seed_provenance =
                   "v2"``; the 1,440 v4 records keep ``"seed_bank_v4"``. No
                   record's ``generator_version`` is rewritten: a merged
                   record was generated by v0.2 and merged by v0.5, and both
                   facts stay legible. The merge's own stamp lives in the
                   manifest;
*   gates        - exact counts, the audited selection, target repetition
                   across all three splits, v4 eval content/membership
                   identity (hashed with the system metadata excluded),
                   disjoint seed namespaces, and provenance. Any gate failing
                   means REFUSE TO WRITE.

Run: python TESTS/training/build_dataset_v5.py [outdir]
"""

